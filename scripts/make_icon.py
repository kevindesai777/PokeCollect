#!/usr/bin/env python3
"""Generate the launcher icon and the Play Store icon from one spec.

    python3 scripts/make_icon.py

Writes androidApp/src/main/res/drawable/ic_launcher_{foreground,monochrome}.xml, the background
colour in androidApp/src/main/res/values/colors.xml and play/graphics/icon-play.svg. Render the
Play icon (512x512, 32-bit PNG) with Chrome:

    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" --headless=new --hide-scrollbars \
      --default-background-color=00000000 --window-size=512,512 \
      --screenshot=$PWD/play/graphics/icon-512.png file://$PWD/play/graphics/icon-play.svg

Chrome writes RGB for an opaque page; Play asks for 32-bit, so re-encode it with an alpha channel.
The design is our own drawing of a dex-style face (lens, three lights, the notched bezel, speaker
slits), chosen by Kevin on 2026-10-26: no sprite, Poke Ball or official logo (play/listing.md).
"""
import os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
INK, RED, DARK_RED = "#000000", "#DC0A2D", "#B3081F"
LENS, LENS_RIM, GLINT = "#30A7D7", "#FFFFFF", "#D2F1FF"
LIGHTS = ("#FF5A5A", "#FFCB05", "#3BD16F")
BG = RED

def circle(cx, cy, r):
    return f"M{cx-r:g},{cy:g}a{r:g},{r:g} 0 1 0 {2*r:g},0a{r:g},{r:g} 0 1 0 {-2*r:g},0z"

# The notched line where the lid meets the body: full width, so masks crop it, never the lens.
BEZEL = "M0,63H45L53,55H108"

# Each element: (path, fill, stroke, strokeWidth, round caps, in the themed-icon layer).
# On the 108-unit adaptive canvas; everything that matters stays inside the 66-unit safe circle.
ELEMENTS = [
    (BEZEL + "V108H0Z", DARK_RED, None, 0, False, False),        # lower body, a shade darker
    (BEZEL, None, INK, 3.5, False, True),
    (circle(41, 42, 12.5), LENS_RIM, INK, 3, False, True),        # lens
    (circle(41, 42, 8.2), LENS, INK, 2, False, True),
    (circle(38, 39, 2.6), GLINT, None, 0, False, False),
    *[(circle(59.5 + 8.5 * i, 36, 3.3), c, INK, 1.7, False, True) for i, c in enumerate(LIGHTS)],
    *[(f"M{60 + 5 * i:g},{76 + 2 * i:g}l8,-8", None, INK, 2.6, True, True) for i in range(3)],  # speaker slits
]

def layers(mono=False):
    if not mono:
        return ELEMENTS
    # Android tints this layer with one colour, so only shapes count: rims become outlines,
    # the lens and lights solid dots.
    out = []
    for p, fill, stroke, sw, cap, keep in ELEMENTS:
        if not keep:
            continue
        solid = fill not in (None, LENS_RIM)
        out.append((p, INK if solid else None, INK if stroke and not solid else None, sw, cap, keep))
    return out

def svg(L, viewbox="0 0 108 108", size=108):
    s = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" width="{size}" height="{size}">',
         f'<rect width="108" height="108" fill="{BG}"/>']
    for p, fill, stroke, sw, cap, _ in L:
        a = [f'd="{p}"', f'fill="{fill or "none"}"']
        if stroke: a += [f'stroke="{stroke}"', f'stroke-width="{sw:g}"', 'stroke-linejoin="round"']
        if cap: a.append('stroke-linecap="round"')
        s.append("<path " + " ".join(a) + "/>")
    s.append("</svg>")
    return "\n".join(s)

def vector(L, comment):
    s = ['<?xml version="1.0" encoding="utf-8"?>', f'<!-- {comment} -->',
         '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
         '    android:width="108dp"', '    android:height="108dp"',
         '    android:viewportWidth="108"', '    android:viewportHeight="108">']
    for p, fill, stroke, sw, cap, _ in L:
        a = [f'android:pathData="{p}"']
        a.append(f'android:fillColor="{fill}"' if fill else 'android:fillColor="#00000000"')
        if stroke:
            a += [f'android:strokeColor="{stroke}"', f'android:strokeWidth="{sw:g}"', 'android:strokeLineJoin="round"']
        if cap: a.append('android:strokeLineCap="round"')
        s.append("    <path\n        " + "\n        ".join(a) + " />")
    s.append("</vector>")
    return "\n".join(s) + "\n"

# What the launcher mask shows (the middle 72 of 108), for the Play 512 icon
open(os.path.join(ROOT, "play/graphics/icon-play.svg"), "w").write(svg(layers(), viewbox="18 18 72 72", size=512))
open(os.path.join(ROOT, "androidApp/src/main/res/drawable/ic_launcher_foreground.xml"), "w").write(
    vector(layers(), "A dex-style face (lens, lights, bezel): our own drawing, generated by scripts/make_icon.py."))
open(os.path.join(ROOT, "androidApp/src/main/res/drawable/ic_launcher_monochrome.xml"), "w").write(
    vector(layers(mono=True), "Themed-icon layer: Android tints it, so only the shape counts."))
open(os.path.join(ROOT, "androidApp/src/main/res/values/colors.xml"), "w").write(
    "<resources>\n    <!-- Generated by scripts/make_icon.py -->\n"
    f'    <color name="ic_launcher_background">{BG}</color>\n</resources>\n')
